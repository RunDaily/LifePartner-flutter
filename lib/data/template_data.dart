  /// 按分类筛选（TemplateCategory.all 返回全部）
  static List<ChecklistTemplate> byCategory(TemplateCategory cat) {
    if (cat == TemplateCategory.all) return all;
    return all.where((t) => t.category == cat).toList();
  }

  /// 精选模板（isFeatured = true）
  static List<ChecklistTemplate> get featured =>
      all.where((t) => t.isFeatured).toList();

  /// 按关键词搜索（标题 + 描述 + 标签）
  static List<ChecklistTemplate> search(String keyword) {
    if (keyword.trim().isEmpty) return all;
    final k = keyword.toLowerCase();
    return all.where((t) {
      return t.title.toLowerCase().contains(k) ||
          t.description.toLowerCase().contains(k) ||
          t.sceneTags.any((tag) => tag.toLowerCase().contains(k));
    }).toList();
  }

